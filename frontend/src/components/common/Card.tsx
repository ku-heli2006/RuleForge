import React from 'react';
import { cn } from '../../lib/utils';

export const Card: React.FC<React.HTMLAttributes<HTMLDivElement>> = ({
  className,
  children,
  ...props
}) => {
  return (
    <div
      className={cn(
        'rounded-lg border border-slate-200 bg-white shadow-xs overflow-hidden transition-all',
        className
      )}
      {...props}
    >
      {children}
    </div>
  );
};

